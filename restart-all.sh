#!/bin/bash
# ═══════════════════════════════════════════════════════════════
# AI-DataHub 数据中台 — 重启脚本
# 用法: ./restart-all.sh [服务名]
# ═══════════════════════════════════════════════════════════════

PROJECT_ROOT="$(cd "$(dirname "$0")" && pwd)"

echo "═══════════════════════════════════════════"
echo "  停止服务..."
echo "═══════════════════════════════════════════"
"$PROJECT_ROOT/stop-all.sh" "$@"

echo ""
echo "═══════════════════════════════════════════"
echo "  启动服务..."
echo "═══════════════════════════════════════════"
"$PROJECT_ROOT/start-all.sh" "$@"
